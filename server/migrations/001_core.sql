CREATE TABLE users (
  id uuid PRIMARY KEY,
  email text NOT NULL UNIQUE CHECK (email = lower(email)),
  display_name text NOT NULL CHECK (length(display_name) BETWEEN 2 AND 80),
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'citizen' CHECK (role IN ('citizen','operator','inspector','analyst','admin')),
  identity_verified boolean NOT NULL DEFAULT false,
  disabled boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE sessions (
  token_hash text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  csrf_token text NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_expiry ON sessions(expires_at);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE TABLE rate_limits (
  key text PRIMARY KEY,
  hits integer NOT NULL,
  expires_at timestamptz NOT NULL
);
CREATE INDEX rate_limits_expiry ON rate_limits(expires_at);
CREATE TABLE operators (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  short_name text NOT NULL
);
CREATE TABLE stations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id integer NOT NULL REFERENCES operators(id),
  name text NOT NULL CHECK (length(name) BETWEEN 2 AND 200),
  area text NOT NULL,
  district text NOT NULL,
  region text NOT NULL CHECK (region IN ('Central','Eastern','Northern','Western')),
  latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  active boolean NOT NULL DEFAULT true,
  demo boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX stations_area ON stations(district, region) WHERE active;
CREATE INDEX stations_coordinates ON stations(latitude, longitude) WHERE active;
CREATE TABLE station_staff (
  user_id uuid NOT NULL REFERENCES users(id),
  station_id integer NOT NULL REFERENCES stations(id),
  PRIMARY KEY(user_id,station_id)
);
CREATE TABLE reports (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id),
  station_id integer NOT NULL REFERENCES stations(id),
  fuel text NOT NULL CHECK (fuel IN ('petrol','diesel','kerosene')),
  price integer NOT NULL CHECK (price BETWEEN 100 AND 100000),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','flagged','verified','rejected','expired')),
  latitude double precision CHECK (latitude BETWEEN -90 AND 90),
  longitude double precision CHECK (longitude BETWEEN -180 AND 180),
  note text NOT NULL DEFAULT '',
  decision_reason text,
  reviewed_by uuid REFERENCES users(id),
  reviewed_at timestamptz,
  idempotency_key uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id,idempotency_key),
  CHECK ((latitude IS NULL) = (longitude IS NULL))
);
CREATE INDEX reports_station ON reports(station_id,fuel,created_at DESC);
CREATE INDEX reports_user ON reports(user_id,created_at DESC);
CREATE INDEX reports_queue ON reports(created_at) WHERE status IN ('pending','flagged');
CREATE TABLE prices (
  station_id integer NOT NULL REFERENCES stations(id),
  fuel text NOT NULL CHECK (fuel IN ('petrol','diesel','kerosene')),
  price integer NOT NULL CHECK (price BETWEEN 100 AND 100000),
  source text NOT NULL CHECK (source IN ('operator','moderator','consensus','demo')),
  report_id uuid REFERENCES reports(id),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(station_id,fuel)
);
CREATE TABLE price_history (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  station_id integer NOT NULL REFERENCES stations(id),
  fuel text NOT NULL CHECK (fuel IN ('petrol','diesel','kerosene')),
  price integer NOT NULL CHECK (price BETWEEN 100 AND 100000),
  source text NOT NULL,
  actor_id uuid REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX history_station ON price_history(station_id,fuel,created_at DESC);
CREATE TABLE subscriptions (
  user_id uuid NOT NULL REFERENCES users(id),
  station_id integer NOT NULL REFERENCES stations(id),
  PRIMARY KEY(user_id,station_id)
);
CREATE TABLE notifications (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id),
  message text NOT NULL,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notifications_user ON notifications(user_id,created_at DESC);
CREATE TABLE tickets (
  id uuid PRIMARY KEY,
  reference text NOT NULL UNIQUE,
  user_id uuid NOT NULL REFERENCES users(id),
  station_id integer NOT NULL REFERENCES stations(id),
  category text NOT NULL CHECK (category IN ('tampering','adulterated','overpricing','refusal','quality','other')),
  vehicle_type text NOT NULL CHECK (vehicle_type IN ('truck','boda','private','other')),
  incident_date date NOT NULL,
  description text NOT NULL CHECK (length(description) BETWEEN 10 AND 5000),
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','investigating','dispatched','resolved','closed')),
  assigned_to uuid REFERENCES users(id),
  due_at timestamptz NOT NULL DEFAULT (now() + interval '24 hours'),
  first_response_at timestamptz,
  resolved_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  version integer NOT NULL DEFAULT 1,
  idempotency_key uuid NOT NULL,
  UNIQUE(user_id,idempotency_key)
);
CREATE INDEX tickets_owner ON tickets(user_id,created_at DESC);
CREATE INDEX tickets_sla ON tickets(due_at) WHERE status NOT IN ('resolved','closed');
CREATE TABLE ticket_messages (
  id uuid PRIMARY KEY,
  ticket_id uuid NOT NULL REFERENCES tickets(id),
  user_id uuid NOT NULL REFERENCES users(id),
  body text NOT NULL CHECK (length(body) BETWEEN 1 AND 3000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ticket_messages_ticket ON ticket_messages(ticket_id,created_at);
CREATE TABLE applications (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id),
  station_id integer NOT NULL REFERENCES stations(id),
  license_reference text NOT NULL CHECK (length(license_reference) BETWEEN 3 AND 200),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  decision_reason text,
  reviewed_by uuid REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX applications_pending ON applications(user_id,station_id) WHERE status='pending';
CREATE TABLE attachments (
  id uuid PRIMARY KEY,
  owner_id uuid NOT NULL REFERENCES users(id),
  ticket_id uuid REFERENCES tickets(id),
  application_id uuid REFERENCES applications(id),
  name text NOT NULL,
  media_type text NOT NULL CHECK (media_type IN ('image/png','image/jpeg','application/pdf')),
  content bytea NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 5242880),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((ticket_id IS NULL) <> (application_id IS NULL))
);
CREATE INDEX attachments_ticket ON attachments(ticket_id);
CREATE INDEX attachments_application ON attachments(application_id);
CREATE TABLE api_tokens (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id),
  station_id integer NOT NULL REFERENCES stations(id),
  name text NOT NULL,
  token_hash text NOT NULL UNIQUE,
  prefix text NOT NULL,
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '90 days'),
  revoked_at timestamptz,
  last_used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE reviews (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id),
  station_id integer NOT NULL REFERENCES stations(id),
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body text NOT NULL CHECK (length(body) <= 2000),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id,station_id)
);
CREATE TABLE rooms (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);
CREATE TABLE messages (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users(id),
  room_id integer NOT NULL REFERENCES rooms(id),
  body text NOT NULL CHECK (length(body) BETWEEN 1 AND 500),
  hidden boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX messages_room ON messages(room_id,created_at DESC);
CREATE TABLE message_votes (
  user_id uuid NOT NULL REFERENCES users(id),
  message_id uuid NOT NULL REFERENCES messages(id),
  PRIMARY KEY(user_id,message_id)
);
CREATE TABLE advisories (
  id uuid PRIMARY KEY,
  author_id uuid NOT NULL REFERENCES users(id),
  title text NOT NULL,
  body text NOT NULL,
  source_url text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE price_caps (
  district text NOT NULL,
  fuel text NOT NULL CHECK (fuel IN ('petrol','diesel','kerosene')),
  price integer NOT NULL CHECK (price BETWEEN 100 AND 100000),
  source_url text NOT NULL,
  effective_from timestamptz NOT NULL,
  effective_until timestamptz NOT NULL,
  updated_by uuid NOT NULL REFERENCES users(id),
  PRIMARY KEY(district,fuel),
  CHECK (effective_until > effective_from)
);
CREATE TABLE town_halls (
  id uuid PRIMARY KEY,
  title text NOT NULL,
  host text NOT NULL,
  starts_at timestamptz NOT NULL,
  created_by uuid NOT NULL REFERENCES users(id)
);
CREATE TABLE questions (
  id uuid PRIMARY KEY,
  hall_id uuid NOT NULL REFERENCES town_halls(id),
  user_id uuid NOT NULL REFERENCES users(id),
  body text NOT NULL,
  answer text,
  answered_by uuid REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE audit_log (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES users(id),
  action text NOT NULL,
  entity_id text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_created ON audit_log(created_at DESC);
CREATE FUNCTION protect_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'audit_log is append-only'; END;
$$;
CREATE TRIGGER audit_no_change BEFORE UPDATE OR DELETE OR TRUNCATE ON audit_log
FOR EACH STATEMENT EXECUTE FUNCTION protect_audit();
